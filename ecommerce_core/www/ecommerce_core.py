"""Context for the Product Sync SPA (www/ecommerce-core.html).

The HTML file itself is generated by the frappe-ui Vite build (the
``frappeui()`` plugin copies the built index.html here with the Jinja boot
block injected). This module supplies the ``boot`` dict that block expands
into ``window[key]`` globals, including the CSRF token the frappe-ui request
layer reads.
"""

import frappe
from frappe import _
from frappe.utils import cstr

no_cache = 1


def get_context(context):
	if frappe.session.user == "Guest":
		frappe.local.flags.redirect_location = "/login?redirect-to=/ecommerce-core"
		raise frappe.Redirect

	# The Product Sync API is System Manager only; fail early instead of
	# rendering a shell whose every request is rejected.
	if "System Manager" not in frappe.get_roles():
		frappe.throw(_("You do not have permission to access Ecommerce Core"), frappe.PermissionError)

	csrf_token = frappe.sessions.get_csrf_token()
	frappe.db.commit()  # page renders are GET, not auto-committed  # nosemgrep: frappe-no-commit

	return {
		"boot": {
			"site_name": frappe.local.site,
			"user": frappe.session.user,
			"csrf_token": csrf_token,
			"socketio_port": frappe.conf.get("socketio_port") or 9000,
			"lang": cstr(frappe.local.lang),
			"app_home": "/ecommerce-core/product-sync",
		}
	}
